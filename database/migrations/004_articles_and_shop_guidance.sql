UPDATE articles SET body = '**Short answer:** most of a warehouse floor can be coated in phases, so the building keeps trading while the work goes on. The plan is the most important part of keeping downtime low.

**Plan the phases.**
1. Divide the floor into bays or wings that can be closed one at a time.
2. Start with the bays that are least used, and leave the dispatch lanes until last.
3. Agree the cure time for each system before the bay is handed back.

**Choose a system for the cure time you can afford.** Some systems need a few days before heavy traffic, while fast-cure polyaspartic topcoats can be walked on and driven on much sooner. Choose the system by how soon the floor must carry forklifts, not by the price per square metre alone.

**Control the dust.** Grinding produces fine dust. Use dust extraction on the grinders, seal the bay from the rest of the building, and clean the area before any coating is applied.

**Work with the shifts.** Night and weekend work often keeps production running and can reduce disruption. Confirm the shifts and the access routes with the operations team in writing.

**Protect the work.** Lay barriers, label the wet areas and agree which routes stay open. Once the floor is handed back, keep traffic off it until the cure time has passed.

Ask us for a phased programme for your site. We will show the bay order, the cure times and the expected handover dates before work starts.'
