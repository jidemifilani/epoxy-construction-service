UPDATE articles SET body = '**Short answer:** epoxy can often be installed over sound ceramic tile, but only when the tiles are firmly bonded and the surface can be prepared. Loose, hollow or cracked tiles must be removed first.

**The bond test.** We check each area by tapping the tiles and by testing the adhesion with a pull test on a sample area. Hollow tiles that sound dull under the tap are a sign of failure underneath, and they will lift the coating later.

**When the tile must come up.**
- Tiles that move or rock when pressed
- Tiles that sound hollow across a large area
- Cracked tiles or loose grout over a wide area
- Tiles with a glazed surface that cannot be keyed for the bond

**Preparing the surface.** Tiles are roughened by grinding to a profile that the epoxy can bond to. Grout lines are then filled and levelled, so the final surface is flat.

**Cost compared with removal.** Leaving sound tile in place is usually cheaper than removing it, because removal creates dust, damage and extra work to level the slab underneath. The savings only hold if the tile is sound.

Book a site visit and we will test the tile and tell you whether it can stay.'
