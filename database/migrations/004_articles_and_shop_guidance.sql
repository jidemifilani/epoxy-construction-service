UPDATE articles SET body = '**Short answer:** a metallic epoxy floor is a clear or coloured base with metallic pigments swirled into it while it is still wet. The result is a flowing, one-off pattern that looks like liquid metal.

**How the pattern is made.** Pigments are added to the wet base coat and moved by hand, using tools and sometimes heat or air, before the topcoat is applied. Because the movement is manual, no two floors are the same, and the finish cannot be copied exactly from a sample.

**Colour choices.** Pearl, silver, copper and bronze are the most common. Deep blues and greens work well in a home entrance or a showroom. Lighter shades show more dust and need regular cleaning in busy areas.

**Living with a metallic floor.**
1. Clean with a soft broom and a pH-neutral cleaner.
2. Avoid abrasive pads and strong solvents, which dull the topcoat.
3. Wipe up spills promptly, especially oils and dyes.
4. Expect light scratches over time. A new topcoat can refresh the finish when needed.

**Cost compared with stone.** A metallic epoxy floor usually costs less than natural stone or a poured terrazzo floor of the same size, but the exact difference depends on the area, the preparation and the finish. Ask for a line-itemed quote and a physical sample before you decide.'
