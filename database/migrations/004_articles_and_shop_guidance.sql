UPDATE articles SET body = '**Short answer:** a simple routine keeps an epoxy floor looking good. Sweep or vacuum regularly, mop with a pH-neutral cleaner, and deal with spills at once.

**Weekly routine.**
1. Sweep or vacuum grit and dust, which can scratch the topcoat when walked on.
2. Mop with warm water and a pH-neutral cleaner made for epoxy floors.
3. Rinse with clean water and let the floor dry.

**Cleaners to avoid.** Strong acids, abrasive scourers, and harsh solvents can dull or damage the topcoat. Ask for the product data sheet for your floor if you are unsure.

**Dealing with spills.**
- Wipe oil, fuel and dye up straight away with a dry cloth
- Clean the area with the same cleaner used for mopping
- Do not let spills dry on the surface

**Scratches and chips.** Small scratches can often be polished out of a gloss topcoat. Deeper chips need a repair with the matching system, and the repair should be done by someone who knows the system.

**When to recoat.** Typical intervals depend on traffic, but the topcoat is the part that wears. When the surface looks dull across the walkways, a topcoat refresh restores the finish without redoing the base.

Keep the product data sheet and the care instructions from your handover with the warranty, so anyone maintaining the floor knows what to use.'
